export interface DailyEmployeeRevenueSessionRecord {
    id?: number;
    store_name: string;
    report_date: string;
    session_time: string;
    screenshot_time_str?: string;
    employee_count: number;
    total_revenue_qd: number;
    total_revenue_actual: number;
    total_installment: number;
    total_quantity: number;
    records: ParsedEmployeeRevenue[];
    raw_info?: Record<string, any>;
    created_at?: string;
    updated_at?: string;
    updated_by?: string;
}

const getCacheKey = (storeName: string, reportDate: string) =>
    `saleshub_daily_emp_rev_cache_${storeName}_${reportDate}`;

/**
 * Tải phiên doanh thu ngày của nhân viên theo Siêu Thị và Ngày chốt
 */
export async function fetchDailyEmployeeSession(
    storeName: string,
    reportDate: string
): Promise<{
    success: boolean;
    data: DailyEmployeeRevenueSessionRecord | null;
    isTableMissing?: boolean;
    error?: string;
}> {
    if (!storeName || !reportDate) {
        return { success: false, data: null };
    }

    try {
        const { data, error } = await supabase
            .from('daily_employee_revenue_sessions')
            .select('*')
            .eq('store_name', storeName)
            .eq('report_date', reportDate)
            .maybeSingle();

        if (error) {
            const isMissing = error.code === 'PGRST205' ||
                error.code === '42P01' ||
                error.message?.includes('does not exist') ||
                error.message?.includes('schema cache');

            if (isMissing) {
                const cached = getCachedDailyEmployeeSession(storeName, reportDate);
                return { success: false, data: cached, isTableMissing: true, error: error.message };
            }

            console.error('Lỗi fetchDailyEmployeeSession:', error);
            const cached = getCachedDailyEmployeeSession(storeName, reportDate);
            return { success: false, data: cached, error: error.message };
        }

        if (data) {
            const record = data as DailyEmployeeRevenueSessionRecord;
            try {
                localStorage.setItem(getCacheKey(storeName, reportDate), JSON.stringify(record));
            } catch {}
            return { success: true, data: record };
        }

        // Nếu storeName === 'all' và chưa có bản ghi 'all' riêng, thử tổng hợp từ các siêu thị thành viên trong cụm
        if (storeName === 'all') {
            const { data: storeSessions, error: storeErr } = await supabase
                .from('daily_employee_revenue_sessions')
                .select('*')
                .neq('store_name', 'all')
                .eq('report_date', reportDate);

            if (!storeErr && storeSessions && storeSessions.length > 0) {
                const aggregatedRecords: ParsedEmployeeRevenue[] = [];
                let totalQd = 0;
                let totalActual = 0;
                let totalInstallment = 0;
                let totalQuantity = 0;

                storeSessions.forEach((s: any) => {
                    if (Array.isArray(s.records)) {
                        aggregatedRecords.push(...s.records);
                    }
                    totalQd += Number(s.total_revenue_qd || 0);
                    totalActual += Number(s.total_revenue_actual || 0);
                    totalInstallment += Number(s.total_installment || 0);
                    totalQuantity += Number(s.total_quantity || 0);
                });

                const aggregated: DailyEmployeeRevenueSessionRecord = {
                    store_name: 'all',
                    report_date: reportDate,
                    session_time: storeSessions[0].session_time || new Date().toISOString(),
                    screenshot_time_str: storeSessions[0].screenshot_time_str,
                    employee_count: aggregatedRecords.length,
                    total_revenue_qd: totalQd,
                    total_revenue_actual: totalActual,
                    total_installment: totalInstallment,
                    total_quantity: totalQuantity,
                    records: aggregatedRecords,
                    raw_info: { source: 'AGGREGATED_CLUSTER_STORES' },
                    updated_at: storeSessions[0].updated_at,
                    updated_by: 'Cụm siêu thị'
                };
                return { success: true, data: aggregated };
            }
        }

        // Không tìm thấy trên Cloud -> thử cache
        const cached = getCachedDailyEmployeeSession(storeName, reportDate);
        return { success: true, data: cached };
    } catch (err: any) {
        console.error('Ngoại lệ khi gọi Supabase daily_employee_revenue_sessions:', err);
        const cached = getCachedDailyEmployeeSession(storeName, reportDate);
        return { success: false, data: cached, error: err?.message || 'Lỗi kết nối' };
    }
}

/**
 * Đọc phiên từ cache local
 */
export function getCachedDailyEmployeeSession(
    storeName: string,
    reportDate: string
): DailyEmployeeRevenueSessionRecord | null {
    try {
        const raw = localStorage.getItem(getCacheKey(storeName, reportDate));
        if (!raw) return null;
        return JSON.parse(raw);
    } catch {
        return null;
    }
}

/**
 * Lưu / Upsert phiên doanh thu ngày của nhân viên lên Supabase Cloud
 */
export async function saveDailyEmployeeSession(
    session: DailyEmployeeRevenueSessionRecord,
    userName: string = 'ADMIN'
): Promise<{ success: boolean; isTableMissing?: boolean; error?: string }> {
    if (!session || !session.store_name || !session.report_date) {
        return { success: false, error: 'Thiếu thông tin siêu thị hoặc ngày báo cáo.' };
    }

    const nowIso = new Date().toISOString();
    const defaultTimeStr = `${new Date().toLocaleTimeString('vi-VN', { hour: '2-digit', minute: '2-digit' })} ${formatDate(session.report_date)}`;

    const payload = {
        store_name: session.store_name,
        report_date: session.report_date,
        session_time: session.session_time || nowIso,
        screenshot_time_str: session.screenshot_time_str || defaultTimeStr,
        employee_count: session.employee_count || session.records?.length || 0,
        total_revenue_qd: session.total_revenue_qd || 0,
        total_revenue_actual: session.total_revenue_actual || 0,
        total_installment: session.total_installment || 0,
        total_quantity: session.total_quantity || 0,
        records: session.records || [],
        raw_info: session.raw_info || {},
        updated_at: nowIso,
        updated_by: userName
    };

    // 1. Cập nhật local cache trước
    try {
        localStorage.setItem(getCacheKey(session.store_name, session.report_date), JSON.stringify(payload));
    } catch {}

    // 2. Upsert Supabase Cloud
    try {
        const { error } = await supabase
            .from('daily_employee_revenue_sessions')
            .upsert([payload], { onConflict: 'store_name,report_date' });

        if (error) {
            const isMissing = error.code === 'PGRST205' ||
                error.code === '42P01' ||
                error.message?.includes('does not exist') ||
                error.message?.includes('schema cache');

            if (isMissing) {
                return { success: false, isTableMissing: true, error: 'Bảng daily_employee_revenue_sessions chưa được tạo trên Supabase.' };
            }
            return { success: false, error: error.message };
        }

        return { success: true };
    } catch (err: any) {
        return { success: false, error: err?.message || 'Lỗi khi lưu Supabase' };
    }
}

/**
 * Lưu phiên Doanh thu ngày cho Cụm nhiều siêu thị:
 * 1. Lưu phiên tổng hợp với store_name = 'all'
 * 2. Tự động nhóm nhân viên theo store_name trong danh bạ và lưu phiên riêng cho từng siêu thị trong cụm
 */
export async function saveClusterDailyEmployeeSessions(
    session: DailyEmployeeRevenueSessionRecord,
    employeesDirectory: { employee_id?: string; store_name?: string }[] = [],
    userName: string = 'ADMIN'
): Promise<{ success: boolean; affectedStores: string[]; isTableMissing?: boolean; error?: string }> {
    if (!session || !session.records || session.records.length === 0) {
        return { success: false, affectedStores: [], error: 'Không có dữ liệu nhân viên để phân bổ.' };
    }

    const empStoreMap: Record<string, string> = {};
    employeesDirectory.forEach(emp => {
        if (emp.employee_id) {
            empStoreMap[emp.employee_id.trim()] = emp.store_name || '';
        }
    });

    // 1. Lưu phiên tổng hợp 'all'
    const masterRes = await saveDailyEmployeeSession(
        { ...session, store_name: 'all' },
        userName
    );

    if (!masterRes.success) {
        return {
            success: false,
            affectedStores: [],
            isTableMissing: masterRes.isTableMissing,
            error: masterRes.error
        };
    }

    const affectedStores: string[] = ['all'];

    // 2. Nhóm nhân viên theo từng siêu thị
    const storeMap: Record<string, ParsedEmployeeRevenue[]> = {};
    session.records.forEach(rec => {
        const store = empStoreMap[rec.employee_id.trim()];
        if (store) {
            if (!storeMap[store]) storeMap[store] = [];
            storeMap[store].push(rec);
        }
    });

    // 3. Lưu phiên riêng cho từng siêu thị thành viên trong cụm
    for (const [storeName, storeRecords] of Object.entries(storeMap)) {
        const totalQd = storeRecords.reduce((acc, r) => acc + (r.revenue_qd || 0), 0);
        const totalActual = storeRecords.reduce((acc, r) => acc + (r.revenue_actual || 0), 0);
        const totalInstallment = storeRecords.reduce((acc, r) => acc + (r.installment_revenue || 0), 0);
        const totalQty = storeRecords.reduce((acc, r) => acc + (r.quantity || 0), 0);

        const storeSession: DailyEmployeeRevenueSessionRecord = {
            store_name: storeName,
            report_date: session.report_date,
            session_time: session.session_time,
            screenshot_time_str: session.screenshot_time_str,
            employee_count: storeRecords.length,
            total_revenue_qd: totalQd,
            total_revenue_actual: totalActual,
            total_installment: totalInstallment,
            total_quantity: totalQty,
            records: storeRecords,
            raw_info: {
                ...session.raw_info,
                source: 'CLUSTER_AUTO_DISTRIBUTION',
                master_store: 'all'
            },
            updated_by: userName
        };

        const res = await saveDailyEmployeeSession(storeSession, userName);
        if (res.success) {
            affectedStores.push(storeName);
        }
    }

    return { success: true, affectedStores };
}
