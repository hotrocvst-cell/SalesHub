export const REALTIME_STORE_SESSIONS_SQL = `-- Bảng lưu trữ phiên dữ liệu Realtime độc lập (mỗi cụm / siêu thị chỉ lưu 1 phiên duy nhất)
CREATE TABLE IF NOT EXISTS public.realtime_store_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_name TEXT NOT NULL UNIQUE,              -- Ràng buộc UNIQUE: mỗi siêu thị/cụm duy nhất 1 phiên
    session_time TIMESTAMPTZ DEFAULT NOW(),       -- Thời gian của phiên realtime (lấy từ giờ chụp ảnh OCR hoặc lúc nạp)
    screenshot_time_str TEXT,                     -- Chuỗi giờ hiển thị gốc trên ảnh (ví dụ "17:19:12 30/10/2026")
    revenue_data JSONB DEFAULT '{}'::jsonb,       -- Số liệu Doanh thu (DTQĐ, Target, DT Thực, Trả góp, % Trả góp...)
    emulation_data JSONB DEFAULT '[]'::jsonb,     -- Danh sách chỉ tiêu thi đua (campaigns list)
    raw_ocr_info JSONB DEFAULT '{}'::jsonb,       -- Ghi chú, engine OCR đã sử dụng
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    updated_by TEXT DEFAULT 'ADMIN'
);

-- Bật Row Level Security & phân quyền truy cập
ALTER TABLE public.realtime_store_sessions ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public read access" ON public.realtime_store_sessions FOR SELECT USING (true);
CREATE POLICY "Allow public insert/update access" ON public.realtime_store_sessions FOR ALL USING (true);
`;

export const REALTIME_SESSIONS_CACHE_KEY = 'saleshub_realtime_store_sessions_cloud_cache';

export interface RealtimeStoreSessionRecord {
    id?: number;
    store_name: string;
    session_time: string;
    screenshot_time_str?: string;
    revenue_data: RevenueItem | Record<string, any>;
    emulation_data: CampaignItem[] | any[];
    raw_ocr_info?: Record<string, any>;
    updated_at?: string;
    updated_by?: string;
}

export interface RealtimeSessionSummary {
    sessionTime: string;
    screenshotTimeStr: string;
    updatedAt: string;
    storeCount: number;
    campaignCount: number;
    isCloud: boolean;
}

/**
 * Tải toàn bộ các phiên Realtime từ Supabase Cloud
 */
export async function fetchRealtimeStoreSessions(): Promise<{
    success: boolean;
    data: RealtimeStoreSessionRecord[];
    isTableMissing?: boolean;
    error?: string;
}> {
    try {
        const { data, error } = await supabase
            .from('realtime_store_sessions')
            .select('*')
            .order('store_name', { ascending: true });

        if (error) {
            // Lỗi PGRST205 hoặc 42P01: Bảng chưa được tạo
            const isMissing = error.code === 'PGRST205' ||
                error.code === '42P01' ||
                error.message?.includes('does not exist') ||
                error.message?.includes('schema cache');

            if (isMissing) {
                console.warn('⚠️ Bảng realtime_store_sessions chưa được tạo trên Supabase Cloud.');
                const cached = getCachedRealtimeSessions();
                return { success: false, data: cached, isTableMissing: true, error: error.message };
            }

            console.error('Lỗi khi tải realtime_store_sessions:', error);
            const cached = getCachedRealtimeSessions();
            return { success: false, data: cached, error: error.message };
        }

        const records = (data || []) as RealtimeStoreSessionRecord[];

        // Cập nhật bộ nhớ đệm LocalStorage làm dự phòng offline
        if (records.length > 0) {
            try {
                localStorage.setItem(REALTIME_SESSIONS_CACHE_KEY, JSON.stringify(records));
            } catch (err) {
                console.warn('Không thể lưu cache realtime sessions vào localStorage', err);
            }
        }

        return { success: true, data: records };
    } catch (err: any) {
        console.error('Ngoại lệ khi gọi Supabase realtime_store_sessions:', err);
        const cached = getCachedRealtimeSessions();
        return { success: false, data: cached, error: err?.message || 'Lỗi kết nối' };
    }
}

/**
 * Đọc phiên từ cache LocalStorage
 */
export function getCachedRealtimeSessions(): RealtimeStoreSessionRecord[] {
    try {
        const raw = localStorage.getItem(REALTIME_SESSIONS_CACHE_KEY);
        if (!raw) return [];
        return JSON.parse(raw);
    } catch {
        return [];
    }
}

/**
 * Lưu / Upsert danh sách phiên Realtime lên Supabase Cloud
 * Ràng buộc UNIQUE(store_name) đảm bảo mỗi siêu thị chỉ lưu 1 phiên duy nhất.
 */
export async function saveRealtimeStoreSessions(
    sessions: RealtimeStoreSessionRecord[],
    userName: string = 'ADMIN'
): Promise<{ success: boolean; isTableMissing?: boolean; error?: string }> {
    if (!sessions || sessions.length === 0) {
        return { success: false, error: 'Không có dữ liệu phiên để lưu.' };
    }

    const payload = sessions.map(s => ({
        store_name: s.store_name,
        session_time: s.session_time || new Date().toISOString(),
        screenshot_time_str: s.screenshot_time_str || null,
        revenue_data: s.revenue_data || {},
        emulation_data: s.emulation_data || [],
        raw_ocr_info: s.raw_ocr_info || {},
        updated_at: new Date().toISOString(),
        updated_by: userName
    }));

    try {
        // Cập nhật cache local trước
        try {
            localStorage.setItem(REALTIME_SESSIONS_CACHE_KEY, JSON.stringify(payload));
        } catch {}

        const { error } = await supabase
            .from('realtime_store_sessions')
            .upsert(payload, { onConflict: 'store_name' });

        if (error) {
            const isMissing = error.code === 'PGRST205' ||
                error.code === '42P01' ||
                error.message?.includes('does not exist') ||
                error.message?.includes('schema cache');

            if (isMissing) {
                return { success: false, isTableMissing: true, error: 'Bảng realtime_store_sessions chưa được tạo trên Supabase.' };
            }
            return { success: false, error: error.message };
        }

        return { success: true };
    } catch (err: any) {
        return { success: false, error: err?.message || 'Lỗi khi lưu Supabase' };
    }
}

/**
 * Chuyển đổi dữ liệu StoreReportingData[] (từ OCR / Nhập tay) thành RealtimeStoreSessionRecord[]
 */
export function convertStoreReportingDataToSessions(
    storesData: StoreReportingData[],
    screenshotTimeStr: string = '',
    campaignDict: CampaignDictItem[] = [],
    userName: string = 'ADMIN'
): RealtimeStoreSessionRecord[] {
    const nowIso = new Date().toISOString();

    return storesData.map(s => {
        const revItem: RevenueItem = {
            store: s.storeRawName,
            shortName: s.storeShortName || getShortStoreName(s.storeRawName),
            sl: Number(s.quantityQd || s.quantityReal || 0),
            rev: Number(s.revenueQd || 0),
            rawRev: Number(s.revenueQd || 0),
            target: Number(s.targetQd || 0),
            pct: s.completionRateQd !== undefined && s.completionRateQd !== null
                ? Number(s.completionRateQd)
                : (s.targetQd > 0 ? (s.revenueQd / s.targetQd) * 100 : 0),
            pctTraGop: Number(s.installmentRateReal || 0),
            dtTraGop: Number(s.installmentReal || 0),
            isNewFormat: true
        };

        const emulationList: CampaignItem[] = Object.values(s.emulations || {}).map((emu: EmulationOcrItem) => {
            const progName = emu.programName || '';
            const label = getCampaignLabel(progName, campaignDict);
            const tg = Number(emu.target || 0);
            const act = Number(emu.actual || 0);
            const pct = emu.completionRate !== undefined && emu.completionRate !== null
                ? Number(emu.completionRate)
                : (tg > 0 ? (act / tg) * 100 : 0);

            return {
                label,
                rawHeader: progName,
                store: s.storeRawName,
                shortName: s.storeShortName || getShortStoreName(s.storeRawName),
                target: tg,
                actual: act,
                pctHT: pct,
                pctDK: Number(emu.forecastRate || 0)
            };
        });

        return {
            store_name: s.storeRawName,
            session_time: nowIso,
            screenshot_time_str: screenshotTimeStr || `${new Date().toLocaleTimeString('vi-VN', { hour: '2-digit', minute: '2-digit' })} ${formatDate(new Date())}`,
            revenue_data: revItem,
            emulation_data: emulationList,
            raw_ocr_info: {
                revenueReal: s.revenueReal,
                targetReal: s.targetReal,
                quantityReal: s.quantityReal
            },
            updated_at: nowIso,
            updated_by: userName
        };
    });
}

/**
 * Trích xuất dữ liệu Báo cáo (CampaignItem[], RevenueItem map, RevenueItem list) từ danh sách sessions
 */
export function convertSessionsToDailyReportState(
    sessions: RealtimeStoreSessionRecord[],
    campaignDict: CampaignDictItem[] = []
): {
    allData: CampaignItem[];
    revenueData: Record<string, RevenueItem>;
    revenueStores: RevenueItem[];
    sessionSummary: RealtimeSessionSummary | null;
} {
    if (!sessions || sessions.length === 0) {
        return {
            allData: [],
            revenueData: {},
            revenueStores: [],
            sessionSummary: null
        };
    }

    const allData: CampaignItem[] = [];
    const revenueData: Record<string, RevenueItem> = {};
    const revenueStores: RevenueItem[] = [];

    let latestSessionTime = '';
    let latestScreenshotStr = '';
    let latestUpdatedAt = '';

    sessions.forEach(sess => {
        // Cập nhật thông tin thời gian mới nhất
        if (!latestSessionTime || (sess.session_time && sess.session_time > latestSessionTime)) {
            latestSessionTime = sess.session_time;
        }
        if (sess.screenshot_time_str) {
            latestScreenshotStr = sess.screenshot_time_str;
        }
        if (!latestUpdatedAt || (sess.updated_at && sess.updated_at > latestUpdatedAt)) {
            latestUpdatedAt = sess.updated_at;
        }

        // Doanh thu
        if (sess.revenue_data && typeof sess.revenue_data === 'object') {
            const revItem = sess.revenue_data as RevenueItem;
            const shortKey = revItem.shortName || getShortStoreName(sess.store_name);
            revenueData[sess.store_name] = revItem;
            if (shortKey) {
                revenueData[shortKey] = revItem;
            }
            revenueStores.push(revItem);
        }

        // Thi đua
        if (Array.isArray(sess.emulation_data)) {
            sess.emulation_data.forEach((item: CampaignItem) => {
                if (item && item.label) {
                    allData.push({
                        ...item,
                        label: getCampaignLabel(item.label || item.rawHeader || '', campaignDict)
                    });
                }
            });
        }
    });

    const summary: RealtimeSessionSummary = {
        sessionTime: latestSessionTime || new Date().toISOString(),
        screenshotTimeStr: latestScreenshotStr || (latestSessionTime ? new Date(latestSessionTime).toLocaleTimeString('vi-VN', { hour: '2-digit', minute: '2-digit' }) : ''),
        updatedAt: latestUpdatedAt || new Date().toISOString(),
        storeCount: sessions.length,
        campaignCount: allData.length,
        isCloud: true
    };

    return {
        allData,
        revenueData,
        revenueStores,
        sessionSummary: summary
    };
}

